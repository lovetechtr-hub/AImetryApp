package com.djmetry.data.repository

/**
 * Репозиторий с данными вошедшего пользователя (подписки, аналитика, настройки, лента…).
 * [AuthRepository] сбрасывает их при выходе, по 401 и перед входом — следующий аккаунт на этом
 * устройстве не должен увидеть ни одного значения предыдущего.
 */
interface UserScoped {
    suspend fun clearUserData()
}
